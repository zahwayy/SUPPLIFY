-- ============================================================================
-- SUPPLIFY WAREHOUSE MANAGEMENT SYSTEM (WMS)
-- Unified Database Schema (PostgreSQL)
--
-- Konsolidasi menyeluruh dari seluruh migrasi skema (001 s.d. 006):
--   SECTION 1 : Authentication & Partners
--               (users, sessions, suppliers, supplier_appeals)
--   SECTION 2 : Master Data
--               (categories, supplier_categories, products)
--   SECTION 3 : Procurement & Shipping
--               (purchase_orders, purchase_order_items, shipment_details)
--   SECTION 4 : Warehouse Transactions
--               (transactions, transaction_items, handover_details)
--   SECTION 5 : Discrepancy & Stock Control
--               (discrepancy_reports, stock_adjustments, stock_movements)
--   SECTION 6 : Evidence, Audit & Notifications
--               (evidence_files, audit_logs, notifications)
--   SECTION 7 : Indexes
--               (performa kueri & pembatasan aturan bisnis)
-- ============================================================================

BEGIN;


-- ============================================================================
-- SECTION 1 : AUTHENTICATION & PARTNERS
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1.1 users
-- Akun internal gudang dan akun mitra supplier beserta peran aksesnya.
-- ----------------------------------------------------------------------------
CREATE TABLE users (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100) NOT NULL,
    email           VARCHAR(150) NOT NULL UNIQUE,
    phone           VARCHAR(30),
    password_hash   TEXT         NOT NULL,
    role            VARCHAR(20)  NOT NULL CHECK (role IN ('admin', 'manager', 'staff', 'supplier')),
    status          VARCHAR(20)  NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'pending', 'rejected', 'inactive')),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- ----------------------------------------------------------------------------
-- 1.2 sessions
-- Penyimpanan token sesi login (hash) untuk autentikasi HTTP-only cookie.
-- ----------------------------------------------------------------------------
CREATE TABLE sessions (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash      TEXT         NOT NULL UNIQUE,
    expires_at      TIMESTAMPTZ  NOT NULL,
    revoked_at      TIMESTAMPTZ,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- ----------------------------------------------------------------------------
-- 1.3 suppliers
-- Profil perusahaan supplier dan riwayat verifikasi oleh Admin.
-- ----------------------------------------------------------------------------
CREATE TABLE suppliers (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL UNIQUE REFERENCES users(id) ON DELETE RESTRICT,
    company_name        VARCHAR(150) NOT NULL,
    contact_name        VARCHAR(100) NOT NULL,
    phone               VARCHAR(30)  NOT NULL,
    address             TEXT         NOT NULL,
    rejection_reason    TEXT,
    verified_by         BIGINT       REFERENCES users(id) ON DELETE SET NULL,
    verified_at         TIMESTAMPTZ,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- ----------------------------------------------------------------------------
-- 1.4 supplier_appeals
-- Pengajuan banding registrasi supplier yang ditolak (maksimal 1 kali per akun).
-- ----------------------------------------------------------------------------
CREATE TABLE supplier_appeals (
    id                        BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id               BIGINT      NOT NULL REFERENCES suppliers(id) ON DELETE CASCADE,
    submitted_by_user_id      BIGINT      NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    status                    VARCHAR(20) NOT NULL DEFAULT 'submitted' CHECK (
        status IN ('submitted', 'under_review', 'approved', 'rejected')
    ),
    rejection_reason_snapshot TEXT,
    appeal_reason             TEXT        NOT NULL,
    proposed_updates          JSONB       NOT NULL DEFAULT '{}'::jsonb,
    admin_decision_notes      TEXT,
    reviewed_by               BIGINT      REFERENCES users(id) ON DELETE SET NULL,
    reviewed_at               TIMESTAMPTZ,
    created_at                TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at                TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- ============================================================================
-- SECTION 2 : MASTER DATA
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 2.1 categories
-- Pengelompokan utama katalog produk gudang.
-- ----------------------------------------------------------------------------
CREATE TABLE categories (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(20)  UNIQUE,
    name            VARCHAR(100) NOT NULL UNIQUE,
    description     TEXT,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- ----------------------------------------------------------------------------
-- 2.2 supplier_categories
-- Relasi kategori barang yang disediakan oleh masing-masing Supplier.
-- ----------------------------------------------------------------------------
CREATE TABLE supplier_categories (
    supplier_id     BIGINT      NOT NULL REFERENCES suppliers(id) ON DELETE CASCADE,
    category_id     BIGINT      NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (supplier_id, category_id)
);

-- ----------------------------------------------------------------------------
-- 2.3 products
-- Master SKU produk, harga beli, harga jual, stok non-negatif, lokasi rak,
-- gambar produk di /public/images/products, dan batas 4-tier Stock Status.
-- ----------------------------------------------------------------------------
CREATE TABLE products (
    id                  BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id         BIGINT         NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
    sku                 VARCHAR(50)    NOT NULL UNIQUE,
    name                VARCHAR(150)   NOT NULL,
    description         TEXT,
    purchase_price      NUMERIC(14, 2) CHECK (purchase_price IS NULL OR purchase_price >= 0),
    selling_price       NUMERIC(14, 2) CHECK (selling_price IS NULL OR selling_price >= 0),
    stock               INTEGER        NOT NULL DEFAULT 0 CHECK (stock >= 0),
    minimum_stock       INTEGER        CHECK (minimum_stock IS NULL OR minimum_stock >= 0),
    low_stock_threshold INTEGER        CHECK (low_stock_threshold IS NULL OR low_stock_threshold > 0),
    unit                VARCHAR(30),
    rack_location       VARCHAR(50),
    image_path          TEXT,
    deleted_at          TIMESTAMPTZ,
    created_at          TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ    NOT NULL DEFAULT NOW(),

    -- Batas Low wajib lebih besar dari batas Severe (minimum_stock) bila keduanya diatur.
    CONSTRAINT chk_products_threshold_order CHECK (
        minimum_stock IS NULL
        OR low_stock_threshold IS NULL
        OR low_stock_threshold > minimum_stock
    )
);


-- ============================================================================
-- SECTION 3 : PROCUREMENT & SHIPPING
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 3.1 purchase_orders
-- Pesanan restock dari Manager ke Supplier.
-- Alur status: pending -> confirmed/rejected -> in_transit -> inspecting ->
-- received/returned (status legacy dipertahankan untuk kompatibilitas data).
-- Catatan: FK source_discrepancy_id ditambahkan setelah discrepancy_reports.
-- ----------------------------------------------------------------------------
CREATE TABLE purchase_orders (
    id                          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_code                     VARCHAR(30)  NOT NULL UNIQUE,
    supplier_id                 BIGINT       NOT NULL REFERENCES suppliers(id) ON DELETE RESTRICT,
    created_by                  BIGINT       NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    status                      VARCHAR(30)  NOT NULL DEFAULT 'pending' CHECK (
        status IN (
            'pending',
            'confirmed',
            'rejected',
            'in_transit',
            'inspecting',
            'received',
            'returned',
            'processing',
            'preparing',
            'delivered',
            'completed',
            'cancelled'
        )
    ),
    reference_po_id             BIGINT       REFERENCES purchase_orders(id) ON DELETE SET NULL,
    source_discrepancy_id       BIGINT,
    order_date                  DATE         NOT NULL DEFAULT CURRENT_DATE,
    expected_arrival            DATE,
    rejection_reason            TEXT,
    notes                       TEXT,
    confirmed_at                TIMESTAMPTZ,
    received_at                 TIMESTAMPTZ,
    arrival_confirmed_at        TIMESTAMPTZ,
    arrival_confirmed_by        BIGINT       REFERENCES users(id) ON DELETE SET NULL,
    arrival_notes               TEXT,
    inspection_requested_at     TIMESTAMPTZ,
    inspection_requested_by     BIGINT       REFERENCES users(id) ON DELETE SET NULL,
    inspection_request_notes    TEXT,
    supplier_followup_notes     TEXT,
    completed_at                TIMESTAMPTZ,
    completed_by                BIGINT       REFERENCES users(id) ON DELETE SET NULL,
    completion_notes            TEXT,
    created_at                  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at                  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- ----------------------------------------------------------------------------
-- 3.2 purchase_order_items
-- Rincian produk, kuantitas pesanan, dan snapshot harga beli pada PO.
-- ----------------------------------------------------------------------------
CREATE TABLE purchase_order_items (
    id                  BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id   BIGINT         NOT NULL REFERENCES purchase_orders(id) ON DELETE CASCADE,
    product_id          BIGINT         NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    quantity            INTEGER        NOT NULL CHECK (quantity > 0),
    unit_price          NUMERIC(14, 2) CHECK (unit_price IS NULL OR unit_price > 0),

    UNIQUE (purchase_order_id, product_id)
);

-- ----------------------------------------------------------------------------
-- 3.3 shipment_details
-- Informasi kurir, resi, atau alasan tanpa resi dari Supplier untuk tiap PO.
-- ----------------------------------------------------------------------------
CREATE TABLE shipment_details (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id   BIGINT       NOT NULL UNIQUE REFERENCES purchase_orders(id) ON DELETE CASCADE,
    shipped_at          TIMESTAMPTZ,
    courier_name        VARCHAR(120),
    tracking_number     VARCHAR(100),
    no_tracking_reason  TEXT,
    notes               TEXT,
    submitted_by        BIGINT       NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);


-- ============================================================================
-- SECTION 4 : WAREHOUSE TRANSACTIONS
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 4.1 transactions
-- Header transaksi Incoming (terikat PO) dan Outgoing (distribusi/customer).
-- Stok bertambah saat Incoming Approved dan berkurang saat Outgoing Shipped.
-- ----------------------------------------------------------------------------
CREATE TABLE transactions (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_code    VARCHAR(30)  NOT NULL UNIQUE,
    type                VARCHAR(20)  NOT NULL CHECK (type IN ('incoming', 'outgoing')),
    status              VARCHAR(20)  NOT NULL DEFAULT 'pending' CHECK (
        status IN (
            'pending',
            'approved',
            'rejected',
            'shipped',
            'delivered',
            'cancelled'
        )
    ),
    created_by          BIGINT       NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    processed_by        BIGINT       REFERENCES users(id) ON DELETE RESTRICT,
    purchase_order_id   BIGINT       REFERENCES purchase_orders(id) ON DELETE RESTRICT,
    rejection_reason    TEXT,
    notes               TEXT,
    shipment_date       DATE,
    recipient_name      VARCHAR(150),
    transaction_date    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    processed_at        TIMESTAMPTZ,
    shipped_at          TIMESTAMPTZ,
    delivered_at        TIMESTAMPTZ,
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    -- Incoming wajib terhubung ke PO; Outgoing tidak boleh merujuk PO.
    CONSTRAINT chk_transaction_po_type CHECK (
        (type = 'incoming' AND purchase_order_id IS NOT NULL)
        OR (type = 'outgoing' AND purchase_order_id IS NULL)
    ),

    -- Membatasi siklus status sesuai jenis transaksi.
    CONSTRAINT chk_transaction_status_type CHECK (
        (type = 'incoming' AND status IN ('pending', 'approved', 'rejected', 'cancelled'))
        OR (type = 'outgoing' AND status IN ('pending', 'approved', 'rejected', 'shipped', 'delivered', 'cancelled'))
    )
);

-- ----------------------------------------------------------------------------
-- 4.2 transaction_items
-- Rincian item transaksi beserta snapshot harga, hasil pemeriksaan fisik
-- Staff (good/damaged), dan Accepted Quantity yang ditetapkan Manager.
-- ----------------------------------------------------------------------------
CREATE TABLE transaction_items (
    id                  BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id      BIGINT         NOT NULL REFERENCES transactions(id) ON DELETE CASCADE,
    product_id          BIGINT         NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    quantity            INTEGER        NOT NULL CHECK (quantity > 0),
    unit_price          NUMERIC(14, 2) CHECK (unit_price IS NULL OR unit_price > 0),
    good_quantity       INTEGER        CHECK (good_quantity IS NULL OR good_quantity >= 0),
    damaged_quantity    INTEGER        NOT NULL DEFAULT 0 CHECK (damaged_quantity >= 0),
    approved_quantity   INTEGER        CHECK (approved_quantity IS NULL OR approved_quantity >= 0),
    condition_status    VARCHAR(20)    CHECK (
        condition_status IS NULL OR condition_status IN (
            'good',
            'damaged',
            'wrong_item',
            'partial',
            'excess',
            'mixed'
        )
    ),
    discrepancy_action  VARCHAR(40),
    notes               TEXT,
    manager_notes       TEXT,

    UNIQUE (transaction_id, product_id)
);

-- ----------------------------------------------------------------------------
-- 4.3 handover_details
-- Catatan pengiriman aktual oleh Staff saat Outgoing berstatus Shipped.
-- ----------------------------------------------------------------------------
CREATE TABLE handover_details (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id      BIGINT       NOT NULL UNIQUE REFERENCES transactions(id) ON DELETE CASCADE,
    recipient_name      VARCHAR(150) NOT NULL,
    recipient_type      VARCHAR(30)  NOT NULL CHECK (
        recipient_type IN ('internal', 'customer', 'branch', 'external', 'courier')
    ),
    recipient_contact   VARCHAR(100),
    handover_method     VARCHAR(30)  NOT NULL CHECK (handover_method IN ('direct', 'courier')),
    handed_over_by      BIGINT       NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    handed_over_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    courier_name        VARCHAR(120),
    tracking_number     VARCHAR(100),
    notes               TEXT,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);


-- ============================================================================
-- SECTION 5 : DISCREPANCY & STOCK CONTROL
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 5.1 discrepancy_reports
-- Pencatatan selisih/kerusakan barang beserta pelacakan klaim refund manual
-- Manager dan tautan PO baru terpisah (follow_up_po_id).
-- ----------------------------------------------------------------------------
CREATE TABLE discrepancy_reports (
    id                  BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_code          VARCHAR(30)    NOT NULL UNIQUE,
    issue_type          VARCHAR(30)    NOT NULL CHECK (
        issue_type IN (
            'shortage',
            'excess',
            'wrong_item',
            'damaged',
            'lost',
            'not_received',
            'other'
        )
    ),
    source_type         VARCHAR(30)    NOT NULL CHECK (
        source_type IN ('incoming', 'outgoing', 'purchase_order', 'stock_count')
    ),
    transaction_id      BIGINT         REFERENCES transactions(id) ON DELETE RESTRICT,
    purchase_order_id   BIGINT         REFERENCES purchase_orders(id) ON DELETE RESTRICT,
    product_id          BIGINT         NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    expected_quantity   INTEGER,
    inspected_quantity  INTEGER        CHECK (inspected_quantity IS NULL OR inspected_quantity >= 0),
    accepted_quantity   INTEGER        CHECK (accepted_quantity IS NULL OR accepted_quantity >= 0),
    actual_quantity     INTEGER,
    difference          INTEGER,
    description         TEXT           NOT NULL,
    status              VARCHAR(20)    NOT NULL DEFAULT 'open' CHECK (
        status IN ('open', 'investigating', 'resolved', 'closed')
    ),
    refund_status       VARCHAR(20)    NOT NULL DEFAULT 'none' CHECK (
        refund_status IN ('none', 'submitted', 'approved', 'rejected', 'completed')
    ),
    refund_amount       NUMERIC(14, 2) CHECK (refund_amount IS NULL OR refund_amount >= 0),
    refund_notes        TEXT,
    refund_requested_by BIGINT         REFERENCES users(id) ON DELETE SET NULL,
    refund_requested_at TIMESTAMPTZ,
    refund_updated_at   TIMESTAMPTZ,
    follow_up_po_id     BIGINT         REFERENCES purchase_orders(id) ON DELETE SET NULL,
    reported_by         BIGINT         NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    reported_at         TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    investigation_notes TEXT,
    resolution_type     VARCHAR(50),
    resolution_notes    TEXT,
    resolved_by         BIGINT         REFERENCES users(id) ON DELETE RESTRICT,
    resolved_at         TIMESTAMPTZ,

    -- Pada sumber 'incoming', transaction_id wajib terisi dan purchase_order_id opsional ikut tertaut.
    CONSTRAINT chk_discrepancy_source_fk CHECK (
        (source_type = 'incoming' AND transaction_id IS NOT NULL)
        OR (source_type = 'outgoing' AND transaction_id IS NOT NULL AND purchase_order_id IS NULL)
        OR (source_type = 'purchase_order' AND purchase_order_id IS NOT NULL AND transaction_id IS NULL)
        OR (source_type = 'stock_count' AND transaction_id IS NULL AND purchase_order_id IS NULL)
    )
);

-- Penyelesaian circular FK setelah tabel discrepancy_reports tersedia.
ALTER TABLE purchase_orders
    ADD CONSTRAINT purchase_orders_source_discrepancy_id_fkey
    FOREIGN KEY (source_discrepancy_id) REFERENCES discrepancy_reports(id) ON DELETE SET NULL;

-- ----------------------------------------------------------------------------
-- 5.2 stock_adjustments
-- Pengajuan penyesuaian stok manual oleh Staff yang harus ditinjau Manager
-- (dilarang menyetujui/menolak pengajuan sendiri; penolakan wajib alasan).
-- ----------------------------------------------------------------------------
CREATE TABLE stock_adjustments (
    id                  BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    adjustment_code     VARCHAR(30) NOT NULL UNIQUE,
    product_id          BIGINT      NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    discrepancy_id      BIGINT      REFERENCES discrepancy_reports(id) ON DELETE RESTRICT,
    adjustment_type     VARCHAR(30) NOT NULL CHECK (
        adjustment_type IN ('loss', 'damage', 'found', 'correction', 'return', 'other')
    ),
    quantity_delta      INTEGER     NOT NULL CHECK (quantity_delta <> 0),
    reason              TEXT        NOT NULL,
    rejection_reason    TEXT,
    status              VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    requested_by        BIGINT      NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    reviewed_by         BIGINT      REFERENCES users(id) ON DELETE RESTRICT,
    reviewed_at         TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_adjustment_not_self_approval CHECK (
        reviewed_by IS NULL OR reviewed_by <> requested_by
    )
);

-- ----------------------------------------------------------------------------
-- 5.3 stock_movements
-- Buku besar (ledger) seluruh mutasi stok gudang yang menjamin saldo konsisten.
-- ----------------------------------------------------------------------------
CREATE TABLE stock_movements (
    id                  BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          BIGINT      NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    source_type         VARCHAR(30) NOT NULL CHECK (source_type IN ('incoming', 'outgoing', 'adjustment')),
    transaction_id      BIGINT      REFERENCES transactions(id) ON DELETE RESTRICT,
    stock_adjustment_id BIGINT      REFERENCES stock_adjustments(id) ON DELETE RESTRICT,
    movement_type       VARCHAR(30) NOT NULL CHECK (
        movement_type IN ('in', 'out', 'adjustment_in', 'adjustment_out')
    ),
    quantity_delta      INTEGER     NOT NULL CHECK (quantity_delta <> 0),
    stock_before        INTEGER     NOT NULL CHECK (stock_before >= 0),
    stock_after         INTEGER     NOT NULL CHECK (stock_after >= 0),
    created_by          BIGINT      NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    notes               TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_movement_stock_balance CHECK (stock_after = stock_before + quantity_delta),

    CONSTRAINT chk_movement_source_type CHECK (
        (
            source_type = 'incoming'
            AND transaction_id IS NOT NULL
            AND stock_adjustment_id IS NULL
            AND movement_type = 'in'
            AND quantity_delta > 0
        )
        OR (
            source_type = 'outgoing'
            AND transaction_id IS NOT NULL
            AND stock_adjustment_id IS NULL
            AND movement_type = 'out'
            AND quantity_delta < 0
        )
        OR (
            source_type = 'adjustment'
            AND transaction_id IS NULL
            AND stock_adjustment_id IS NOT NULL
            AND (
                (movement_type = 'adjustment_in' AND quantity_delta > 0)
                OR (movement_type = 'adjustment_out' AND quantity_delta < 0)
            )
        )
    )
);


-- ============================================================================
-- SECTION 6 : EVIDENCE, AUDIT & NOTIFICATIONS
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 6.1 evidence_files
-- Metadata berkas bukti operasional (berkas fisik disimpan di object/file storage).
-- ----------------------------------------------------------------------------
CREATE TABLE evidence_files (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type         VARCHAR(40)  NOT NULL CHECK (
        entity_type IN (
            'incoming_inspection',
            'supplier_shipment',
            'supplier_arrival',
            'outgoing_handover',
            'discrepancy'
        )
    ),
    transaction_id      BIGINT       REFERENCES transactions(id) ON DELETE RESTRICT,
    purchase_order_id   BIGINT       REFERENCES purchase_orders(id) ON DELETE RESTRICT,
    discrepancy_id      BIGINT       REFERENCES discrepancy_reports(id) ON DELETE RESTRICT,
    storage_key         TEXT         NOT NULL UNIQUE,
    original_name       VARCHAR(255) NOT NULL,
    mime_type           VARCHAR(100) NOT NULL,
    size_bytes          BIGINT       NOT NULL CHECK (size_bytes > 0),
    description         TEXT,
    uploaded_by         BIGINT       NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_evidence_source_fk CHECK (
        (
            entity_type IN ('incoming_inspection', 'outgoing_handover')
            AND transaction_id IS NOT NULL
            AND purchase_order_id IS NULL
            AND discrepancy_id IS NULL
        )
        OR (
            entity_type IN ('supplier_shipment', 'supplier_arrival')
            AND purchase_order_id IS NOT NULL
            AND transaction_id IS NULL
            AND discrepancy_id IS NULL
        )
        OR (
            entity_type = 'discrepancy'
            AND discrepancy_id IS NOT NULL
            AND transaction_id IS NULL
            AND purchase_order_id IS NULL
        )
    )
);

-- ----------------------------------------------------------------------------
-- 6.2 audit_logs
-- Rekam jejak aktivitas pengguna dan perubahan state entitas penting sistem.
-- ----------------------------------------------------------------------------
CREATE TABLE audit_logs (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id        BIGINT       REFERENCES users(id) ON DELETE SET NULL,
    actor_role      VARCHAR(20),
    action          VARCHAR(100) NOT NULL,
    entity_type     VARCHAR(50)  NOT NULL,
    entity_id       BIGINT,
    previous_state  JSONB,
    new_state       JSONB,
    metadata        JSONB,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- ----------------------------------------------------------------------------
-- 6.3 notifications
-- Notifikasi persisten lintas peran (verifikasi registrasi & pengajuan banding).
-- ----------------------------------------------------------------------------
CREATE TABLE notifications (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    type              VARCHAR(60)  NOT NULL,
    title             VARCHAR(150) NOT NULL,
    message           TEXT         NOT NULL,
    entity_type       VARCHAR(50),
    entity_id         BIGINT,
    href              TEXT,
    is_read           BOOLEAN      NOT NULL DEFAULT FALSE,
    read_at           TIMESTAMPTZ,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);


-- ============================================================================
-- SECTION 7 : INDEXES
-- ============================================================================

-- Authentication, Sessions & Supplier Appeals
CREATE INDEX idx_sessions_user_id ON sessions(user_id);
CREATE INDEX idx_sessions_expires_at ON sessions(expires_at);
CREATE UNIQUE INDEX uq_supplier_appeals_single_per_supplier ON supplier_appeals(supplier_id);
CREATE INDEX idx_supplier_appeals_supplier_created ON supplier_appeals(supplier_id, created_at DESC);
CREATE INDEX idx_supplier_appeals_status_created ON supplier_appeals(status, created_at DESC);

-- Master Data (Categories, Supplier Categories & Products)
CREATE INDEX idx_supplier_categories_category_id ON supplier_categories(category_id);
CREATE INDEX idx_products_category_id ON products(category_id);
CREATE INDEX idx_products_active ON products(id) WHERE deleted_at IS NULL;

-- Procurement (Purchase Orders & Items)
CREATE INDEX idx_po_items_purchase_order ON purchase_order_items(purchase_order_id);
CREATE INDEX idx_po_items_product ON purchase_order_items(product_id);
CREATE INDEX idx_po_supplier_status ON purchase_orders(supplier_id, status);
CREATE INDEX idx_po_reference_po ON purchase_orders(reference_po_id) WHERE reference_po_id IS NOT NULL;
CREATE INDEX idx_po_source_discrepancy ON purchase_orders(source_discrepancy_id) WHERE source_discrepancy_id IS NOT NULL;

-- Warehouse Transactions
CREATE INDEX idx_transactions_type_status_date ON transactions(type, status, transaction_date DESC);
CREATE INDEX idx_transactions_created_by ON transactions(created_by);
CREATE INDEX idx_transactions_purchase_order ON transactions(purchase_order_id) WHERE purchase_order_id IS NOT NULL;
CREATE INDEX idx_transaction_items_transaction ON transaction_items(transaction_id);

-- Menjamin maksimal SATU transaksi Incoming non-rejected (pending atau approved) per PO.
CREATE UNIQUE INDEX uq_transactions_single_active_incoming_po
    ON transactions(purchase_order_id)
    WHERE type = 'incoming'
      AND purchase_order_id IS NOT NULL
      AND status IN ('pending', 'approved');

-- Discrepancy & Stock Control
